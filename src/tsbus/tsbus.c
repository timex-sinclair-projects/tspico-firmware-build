/*
 * tsbus: the TS-Pico v3 card's bus, as a MicroPython module (phase 3 of the v3
 * port plan, docs/v3-firmware-port-plan.md in the tspico-hardware repo).
 *
 * The card has no memory chips: it answers every 2068 memory read it owns
 * from images in SRAM, and the TS-Pico ports 0Eh/0Fh from core 1. This is the
 * phase 1 bus test (firmware/bringup/bus_card.c in tspico-hardware), moved
 * under MicroPython:
 *
 * - PIO0: serve (reads the address off MD, decides through a chunk table,
 *   asserts /BE, pushes a pointer, drives the byte) and io_drive (replies to
 *   IN 0Eh/0Fh). PIO1: addr_read (the address-buffer enables), mem_write
 *   (every memory write) and io_snoop (every I/O write). Both are full.
 * - DMA: ch_ptr takes serve's pointer and triggers ch_data, which copies the
 *   byte into serve's TX FIFO and chains to ch_log, which logs the pointer.
 * - Core 1 runs only this code, from SRAM, with its own vector table: the bank
 *   shadow (ports F4h, FFh) and the chunk table, DOCK writes, the IN handler
 *   on /IORD, and OUTs to 0Eh/0Fh.
 * - Images at TSBUS_IMAGE_REGION (the top 256 KB of SRAM, outside the GC heap;
 *   src/boards/TSPICO_V3/memmap): the byte for (address, slot) is at
 *   IMAGE_REGION + 4 * address + slot. Slots: 0 HOME, 1 EXROM, 2 DOCK.
 *
 * Python API:
 *   tsbus.start()                  250 MHz; claim PIO0, PIO1 and 3 DMA channels;
 *                                  start core 1
 *   tsbus.load(slot, data)         copy data into a slot, repeated to fill 64 KB
 *   tsbus.switch(home=, exrom=, dock=)  replace images: a ROM change resets the
 *                                  2068, a DOCK change alone is live
 *   tsbus.reset()                  hold the 2068 for 200 ms, then release it
 *   tsbus.serve(on)                /BE and U3 live (the 2068 must be held)
 *   tsbus.exrom(on), tsbus.dock(on) serve the EXROM / DOCK banks' chunks
 *   tsbus.hold(on)                 hold the 2068 in reset, or release it
 *   tsbus.stats()                  counters, as a dict
 *   tsbus.MQ()                     v2's MQ over core 1's queues: put, get, tx_fifo,
 *                                  rx_fifo, put_block, status, exec, active
 *
 * Nothing on core 1 may touch flash: LittleFS writes stop execute-in-place,
 * and core 1 is never paused for them (it is not a multicore lockout victim).
 * Its code is __not_in_flash_func and uses registers directly rather than SDK
 * inline helpers, which a size-optimised build may leave out of line in flash.
 */

