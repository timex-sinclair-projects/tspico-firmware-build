#!/usr/bin/env python3
"""Generate src/TS/speech_rules.py: the NRL letter-to-sound rules as data.

    python3 tools/speech-rules.py ENGLISH_C

ENGLISH_C is John A. Wasser's english.c (1985), from the CMU AI Repository's
eng2phon package (areas/speech/systems/eng2phon): the rules of NRL Report
7948, "Automatic Translation of English Text to Phonetics by Means of
Letter-to-Sound Rules" (Elovitz, Johnson, McHugh and Shore, Naval Research
Laboratory, 1976). Both are public domain: a US-government report, and
Wasser's "this is all public domain and I make no copyright claims on it".

The rules become RULES, a dict from the first letter of the text to match
('' for punctuation) to a tuple of (left context, match, right context,
phonemes), in Wasser's order, which the matcher (TS/speech.py) relies on.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "TS", "speech_rules.py")


def val(p):
    p = p.strip()
    if p in ("Anything", "Silent"):
        return ""
    if p in ("Nothing", "Pause"):
        return " "
    m = re.fullmatch(r'"(.*)"', p)
    return m.group(1) if m else None


def main():
    src = open(sys.argv[1]).read()
    assert "NRL Report 7948" in src, "not Wasser's english.c"
    rules = {}
    for block in re.finditer(r"static Rule (\w+)_rules\[\]\s*=\s*\{(.*?)\n\s*\};", src, re.S):
        name, body = block.groups()
        lst = []
        for m in re.finditer(r"\{([^{}]*)\}", body):
            parts = m.group(1).split(",")
            if len(parts) != 4:
                continue
            v = [val(p) for p in parts]
            if None in v:
                continue
            lst.append(tuple(v))
        rules["" if name == "punct" else name] = lst
    n = sum(len(v) for v in rules.values())
    with open(OUT, "w") as f:
        f.write('"""The NRL letter-to-sound rules (NRL Report 7948, 1976), as John A.\n'
                "Wasser coded them in english.c (1985). Both public domain. Generated by\n"
                "tools/speech-rules.py: don't edit.\n\n"
                "RULES[first letter] = ((left, match, right, phonemes), ...), in order.\n"
                "Contexts: # one or more vowels, : zero or more consonants, ^ one\n"
                "consonant, . a voiced consonant (BDVGJLMNRWZ), % a suffix (ER, E, ES, ED,\n"
                "ING, ELY), + a front vowel (E, I, Y), ' ' the edge of the word.\n"
                'Phonemes: upper case are two letters (IY, AE ...), lower case one (p, t ...)."""\n\n')
        f.write("RULES = {\n")
        for k in sorted(rules):
            f.write("    %r: (\n" % k)
            for r in rules[k]:
                f.write("        %r,\n" % (r,))
            f.write("    ),\n")
        f.write("}\n")
    print("wrote %s: %d rules" % (os.path.normpath(OUT), n))


if __name__ == "__main__":
    main()
